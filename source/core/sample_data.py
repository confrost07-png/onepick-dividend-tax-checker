def example_curve(days: int) -> pd.DataFrame:
    """화면 구성을 보여 주기 위한 예시 곡선. 실제 분석값이 아니다.

    중앙값은 완만한 곡선, 25~75% 범위는 날짜가 갈수록 넓어지는 띠로 만든다.
    """
    rows = []
    for d in range(days + 1):
        median = 0.6 * math.sin(d / days * math.pi * 0.8)
        spread = 0.4 + 2.6 * math.sqrt(d / days)
        rows.append({"day": d, "median": round(median, 3), "q25": round(median - spread, 3), "q75": round(median + spread * 0.7, 3)})
    return pd.DataFrame(rows)


