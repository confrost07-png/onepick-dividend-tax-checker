def apply(brackets: list[Bracket], taxable: int) -> int:
    """누진 구간표로 세액을 계산한다. 원 미만은 버린다."""
    if taxable <= 0:
        return 0
    b = max((b for b in brackets if taxable > b.lower_bound or b.lower_bound == 0), key=lambda b: b.lower_bound)
    return b.base_tax + (taxable - b.lower_bound) * b.rate_pct // 100
