def casual(text: str) -> str | None:
    """부르는 말·뜻 없는 글자·불만이면 정해 둔 답, 아니면 None. 점검 답(ㅇㅇ·ㄴㄴ·숫자·회사 이름)은 건드리지 않는다."""
    t = re.sub(r"\s+", "", text)
    if not t or len(t) > 20 or t in _JAMO_ANSWER:
        return None
    letters = re.sub(r"[^가-힣A-Za-z0-9]", "", t)
    if not letters:  # 한글 글자·영문·숫자가 하나도 없음: 'ㅋㅋㅋ', 'ㅠㅠ', '...', '???', 'ㅁㄴㅇㄹ'
        return NOISE_REPLY
    if _CALL.match(re.sub(r"[^가-힣]", "", t)) and not re.search(r"[A-Za-z0-9]", t):
        return CALL_REPLY
    if any(w in t for w in _COMPLAINT):
        return COMPLAINT_REPLY
    return None
