def small_talk(text: str) -> str | None:
    """짧은 인사·정체·사용법 질문이면 정해 둔 답, 아니면 None. 긴 문장(점검 답과 섞인 말)은 건드리지 않는다."""
    t = text.replace(" ", "").lower().rstrip("?!.~ㅋㅎ")
    if not t or len(t) > 15 or any(ch.isdigit() for ch in t):
        return None
    for words, reply in SMALL_TALK:
        # 짧은 말은 뒤에 '요'·'하세요' 같은 꼬리만 붙어야 같은 말로 본다('하이브'·'안녕지주'는 아님)
        if any(t == w or (t.startswith(w) and _TAIL.fullmatch(t[len(w):])) or (len(w) >= 4 and w in t) for w in words):
            return reply
    return None


_TAIL = re.compile(r"(요|세요|하세요|하십니까|해|해요|합니다|니|냐|야|여|어|ㅎ+|ㅋ+)?")


